import { useQuery } from '@tanstack/react-query';
import { useTranslation } from 'react-i18next';
import { CircleCheck, Clock, ReceiptText } from 'lucide-react';
import type { FiscalInfo, PrintDocument } from '@tavolina/shared';
import { EmptyState, Skeleton, cn } from '@tavolina/ui';
import { LanguageSwitch } from '../components/LanguageSwitch';
import { guestApi } from '../lib/api';

interface DigitalReceipt {
  document: PrintDocument;
  fiscal: FiscalInfo | null;
  qrSvg: string | null;
}

/** The receipt behind the QR code / link: the same lines as the paper one, plus the fiscal QR. */
export function ReceiptPage({ token }: { token: string }) {
  const { t } = useTranslation();
  const receipt = useQuery({
    queryKey: ['receipt', token],
    queryFn: () => guestApi<DigitalReceipt>('GET', `/receipts/${token}`),
    // Fiscalization can take a moment; check back until it is registered.
    refetchInterval: (q) => (q.state.data?.fiscal?.status === 'pending' ? 5000 : false),
    retry: 1,
  });
  return (
    <div className="mx-auto flex min-h-dvh max-w-md flex-col gap-4 px-4 py-6">
      <header className="flex items-center justify-between">
        <span className="flex items-center gap-2 text-lg font-extrabold">
          <ReceiptText className="size-5" aria-hidden />
          {t('receipt.title')}
        </span>
        <LanguageSwitch />
      </header>
      {receipt.isLoading ? <Skeleton className="h-[32rem]" /> : null}
      {receipt.isError ? <EmptyState icon={<ReceiptText />} title={t('receipt.notFound')} /> : null}
      {receipt.data ? (
        <>
          <article
            aria-label={t('receipt.title')}
            className="overflow-x-auto rounded-card border border-border bg-white p-4 font-mono text-[13px] leading-snug text-neutral-900 shadow-raised dark:bg-neutral-100"
          >
            {receipt.data.document.lines.map((line, i) => {
              if (line.kind === 'rule')
                return <hr key={i} className="my-1.5 border-dashed border-neutral-400" />;
              if (line.kind === 'feed') return null;
              if (line.kind === 'qr') {
                return receipt.data.qrSvg ? (
                  <div
                    key={i}
                    className="mx-auto my-2 size-40"
                    // Generated by the API from the fiscal verification link.
                    dangerouslySetInnerHTML={{ __html: receipt.data.qrSvg }}
                  />
                ) : null;
              }
              return (
                <p
                  key={i}
                  className={cn(
                    'whitespace-pre',
                    line.align === 'center' && 'text-center',
                    line.align === 'right' && 'text-right',
                    line.bold && 'font-bold',
                    line.size === 'double' && 'text-base font-bold',
                  )}
                >
                  {line.text}
                </p>
              );
            })}
          </article>
          {receipt.data.fiscal ? (
            <p
              className={cn(
                'flex items-center gap-2 rounded-control px-3 py-2 text-sm',
                receipt.data.fiscal.status === 'registered'
                  ? 'bg-success-soft text-success-soft-fg'
                  : 'bg-warning-soft text-warning-soft-fg',
              )}
            >
              {receipt.data.fiscal.status === 'registered' ? (
                <CircleCheck className="size-4" />
              ) : (
                <Clock className="size-4" />
              )}
              {receipt.data.fiscal.status === 'registered'
                ? t('receipt.fiscalized')
                : t('receipt.pending')}
            </p>
          ) : null}
          {receipt.data.fiscal?.qrUrl ? (
            <a
              className="text-center text-sm font-semibold text-primary underline"
              href={receipt.data.fiscal.qrUrl}
              target="_blank"
              rel="noreferrer"
            >
              {t('receipt.verify')}
            </a>
          ) : null}
        </>
      ) : null}
    </div>
  );
}
